//! Protection and audit of the development fee of the combined miner (docs/17-fee-protection.md).
//!
//! What this module does, and what it cannot do:
//!  * the fee ADDRESS is not a string of the program (a hex editor finds nothing) and is checked against a digest at start-up;
//!  * the official Quantus miner shipped with a release is PINNED by its BLAKE3 hash (`quantus-miner.pins`): the node refuses to
//!    run any other `quantus-miner` (a script that ignores the fee address, a patched build, a swap after start-up);
//!  * every few minutes the miner sends a signed BEACON to the project's seed nodes: Vearl account, Quantus address, worker id,
//!    fee percentage, hashes of its own executable and of the Quantus miner. An AUDITOR (deploy/feeaudit) compares the beacons with the
//!    public API of the Quantus pool: the fee worker `vrl-fee-<id>` must show about `fee_pct` % of the Quantus work of `vrl-<id>`.
//!  * this is DETECTION and deterrence, not a lock: the source is open, anybody can build a fork without the fee or mine Quantus
//!    with the official miner directly. What the project controls are its own services (faucet, free compute gateway, pool, listings).
use crate::crypto::*;
use crate::net::{Conn, Msg};
use ed25519_dalek::SigningKey;
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Mutex, OnceLock};
use std::time::Duration;

/// BLAKE3 digest of the fee address (checked at start-up); the address itself is stored masked.
const ADDR_DIGEST: &str = "cdfa3092057706189a3d0c9b563f2d7d1862b01037f7b11b2ed4aad501efc1e2";
const ADDR_MASKED: [u8; 49] = [135, 233, 110, 236, 213, 210, 27, 116, 244, 217, 134, 233, 190, 44, 195, 247, 217, 244, 7, 111, 1, 209, 248, 50, 118, 45, 99, 65, 189, 191, 63, 60, 130, 101, 230, 63, 225, 14, 199, 141, 104, 239, 185, 34, 32, 76, 197, 63, 147];
const MASK_LABEL: &[u8] = b"vearl/fee/mask/v1";
/// "platform hash" lines of the pinned Quantus miner builds (generated by deploy/release/pin_quantus.py).
const PINS: &str = include_str!("../quantus-miner.pins");

fn mask(n: usize) -> Vec<u8> {
    let mut out = vec![0u8; n];
    blake3::Hasher::new_derive_key("vearl/fee/mask").update(MASK_LABEL).finalize_xof().fill(&mut out);
    out
}

/// Bytes -> masked form (used by the maintenance command `vearl-miner fee-obf`).
pub fn mask_address(addr: &str) -> (Vec<u8>, String) {
    let m = mask(addr.len());
    (addr.bytes().zip(m).map(|(a, b)| a ^ b).collect(), hex(blake3::hash(addr.as_bytes()).as_bytes()))
}

pub fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

/// The development fee address, unmasked at run time.
pub fn dev_address() -> String {
    let m = mask(ADDR_MASKED.len());
    String::from_utf8(ADDR_MASKED.iter().zip(m).map(|(a, b)| a ^ b).collect()).unwrap_or_default()
}

/// False if the fee constants were altered in this executable (address digest mismatch).
pub fn fee_constants_ok() -> bool {
    hex(blake3::hash(dev_address().as_bytes()).as_bytes()) == ADDR_DIGEST
}

pub fn file_hash(path: &std::path::Path) -> Result<String, String> {
    let bytes = std::fs::read(path).map_err(|e| format!("{}: {e}", path.display()))?;
    Ok(hex(blake3::hash(&bytes).as_bytes()))
}

/// Pinned hash for this platform (None if the build carries no pin).
fn pinned() -> Option<&'static str> {
    let key = if cfg!(windows) { "windows" } else { "linux" };
    PINS.lines().filter_map(|l| l.split_once(' ')).find(|(k, v)| *k == key && v.len() == 64 && v.bytes().any(|c| c != b'0')).map(|(_, v)| v.trim())
}

/// Checks that `path` is the Quantus miner pinned in this build. Returns its hash.
pub fn verify_quantus_binary(path: &std::path::Path) -> Result<String, String> {
    let want = pinned().ok_or_else(|| "this build carries no pin for the Quantus miner (not an official release build)".to_string())?;
    let got = file_hash(path)?;
    if got == want {
        Ok(got)
    } else {
        Err(format!("{} is not the official Quantus miner of this release (hash {} instead of {}): it was modified or replaced", path.display(), &got[..16], &want[..16]))
    }
}

// ---------------------------------------------------------------- beacons

#[derive(Clone, Debug, Serialize, Deserialize, PartialEq)]
pub struct FeeBeacon {
    pub account: PubKey,
    /// the operator's Quantus payout address
    pub quantus: String,
    /// "abcd1234": first 4 bytes of the Vearl account, in the worker names `vrl-<id>` and `vrl-fee-<id>`
    pub worker_id: String,
    pub share_pct: u32,
    pub fee_pct: u32,
    pub version: String,
    /// BLAKE3 of this executable and of the Quantus miner it drives (the auditor compares them with the official release hashes)
    pub node_hash: String,
    pub quantus_hash: String,
    pub ts: u64,
    pub sig: Vec<u8>,
}

impl FeeBeacon {
    fn digest(&self) -> Hash {
        h(
            "vearl/fee-beacon/v1",
            &[
                &self.account,
                self.quantus.as_bytes(),
                self.worker_id.as_bytes(),
                &self.share_pct.to_le_bytes(),
                &self.fee_pct.to_le_bytes(),
                self.version.as_bytes(),
                self.node_hash.as_bytes(),
                self.quantus_hash.as_bytes(),
                &self.ts.to_le_bytes(),
            ],
        )
    }

    pub fn worker_id_of(account: &PubKey) -> String {
        account.iter().take(4).map(|b| format!("{b:02x}")).collect()
    }

    pub fn new(sk: &SigningKey, quantus: &str, share_pct: u32, node_hash: String, quantus_hash: String, now: u64) -> FeeBeacon {
        let account = pubkey(sk);
        let mut b = FeeBeacon {
            account,
            quantus: quantus.to_string(),
            worker_id: Self::worker_id_of(&account),
            share_pct,
            fee_pct: crate::dual::QTC_FEE_PCT,
            version: env!("CARGO_PKG_VERSION").to_string(),
            node_hash,
            quantus_hash,
            ts: now,
            sig: vec![],
        };
        b.sig = sign(sk, &b.digest());
        b
    }

    /// Format, binding of the worker id to the account, freshness (+/- 10 min) and signature.
    pub fn verify(&self, now: u64) -> Result<(), String> {
        if !crate::dual::valid_qtc_address(&self.quantus) {
            return Err("bad Quantus address".into());
        }
        if self.worker_id != Self::worker_id_of(&self.account) {
            return Err("worker id does not match the account".into());
        }
        if self.version.len() > 32 || self.node_hash.len() != 64 || self.quantus_hash.len() != 64 || self.share_pct > 100 || self.fee_pct > 100 {
            return Err("bad field".into());
        }
        if self.ts + 600 < now || self.ts > now + 600 {
            return Err("stale or future beacon".into());
        }
        if !verify_sig(&self.account, &self.digest(), &self.sig) {
            return Err("bad signature".into());
        }
        Ok(())
    }
}

/// Registry kept by seed nodes started with `--collect-fee-beacons` (newest beacon per account).
static REGISTRY: OnceLock<Mutex<HashMap<PubKey, FeeBeacon>>> = OnceLock::new();
static COLLECT: AtomicBool = AtomicBool::new(false);
const REGISTRY_MAX: usize = 50_000;

pub fn set_collecting(on: bool) {
    COLLECT.store(on, Ordering::SeqCst);
}

pub fn collecting() -> bool {
    COLLECT.load(Ordering::SeqCst)
}

fn registry() -> &'static Mutex<HashMap<PubKey, FeeBeacon>> {
    REGISTRY.get_or_init(|| Mutex::new(HashMap::new()))
}

/// Seed side: validates and stores a beacon. Nodes that do not collect refuse (the content is never relayed).
pub fn record_beacon(b: &FeeBeacon, now: u64) -> Result<(), String> {
    if !collecting() {
        return Err("this node does not collect fee beacons".into());
    }
    b.verify(now)?;
    let mut r = registry().lock().unwrap();
    if let Some(old) = r.get(&b.account) {
        if old.ts >= b.ts {
            return Ok(()); // replay or older
        }
    } else if r.len() >= REGISTRY_MAX {
        let oldest = r.iter().min_by_key(|(_, v)| v.ts).map(|(k, _)| *k);
        if let Some(k) = oldest {
            r.remove(&k);
        }
    }
    r.insert(b.account, b.clone());
    Ok(())
}

pub fn beacons_json(now: u64) -> serde_json::Value {
    let r = registry().lock().unwrap();
    let mut v: Vec<&FeeBeacon> = r.values().collect();
    v.sort_by_key(|b| std::cmp::Reverse(b.ts));
    serde_json::json!({
        "count": v.len(),
        "beacons": v.iter().map(|b| serde_json::json!({
            "account": hex(&b.account), "vearl_address": crate::wallet::address_of(&b.account), "quantus": b.quantus, "worker_id": b.worker_id,
            "share_pct": b.share_pct, "fee_pct": b.fee_pct, "version": b.version, "node_hash": b.node_hash, "quantus_hash": b.quantus_hash,
            "ts": b.ts, "age_s": now.saturating_sub(b.ts),
        })).collect::<Vec<_>>(),
    })
}

pub fn registry_len() -> usize {
    registry().lock().unwrap().len()
}

pub fn clear_registry() {
    registry().lock().unwrap().clear();
}

/// Miner side: sends the beacon to one seed (`host:port@noise_public_key_hex`). The seed's Noise key is checked when pinned.
pub fn send_beacon(seed_spec: &str, b: &FeeBeacon) -> Result<(), String> {
    let (addr, pin) = match seed_spec.split_once('@') {
        Some((a, k)) => (a, Some(k)),
        None => (seed_spec, None),
    };
    let mut c = Conn::connect(addr).map_err(|e| format!("{addr}: {e}"))?;
    if let Some(k) = pin {
        if hex(&c.remote) != k.to_lowercase() {
            return Err(format!("{addr}: the seed's network key does not match the pinned key"));
        }
    }
    c.set_timeout(Duration::from_secs(10));
    c.send(&Msg::FeeBeacon(b.clone())).map_err(|e| e.to_string())?;
    loop {
        match c.recv().map_err(|e| e.to_string())? {
            Msg::Hello { .. } => continue,
            Msg::Ack { ok: true, .. } => return Ok(()),
            Msg::Ack { ok: false, info } => return Err(info),
            _ => return Err("unexpected reply".into()),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sk(b: u8) -> SigningKey {
        SigningKey::from_bytes(&[b; 32])
    }
    const Q: &str = "qzm7tR2aEJEdMFajwDspjiWefz2F4iDzsys32gE1DK8Dxc59P";

    #[test]
    fn the_fee_address_is_intact_and_not_a_plain_string() {
        assert_eq!(dev_address(), Q);
        assert!(fee_constants_ok());
        // the masked bytes do not contain any 6-letter window of the address
        assert!(!ADDR_MASKED.windows(6).any(|w| w == &Q.as_bytes()[..6]));
        assert_eq!(crate::dual::QTC_FEE_PCT, 10);
    }

    #[test]
    fn only_the_pinned_quantus_miner_is_accepted() {
        let d = std::env::temp_dir().join(format!("vearl-pin-{}", rand::random::<u32>()));
        std::fs::create_dir_all(&d).unwrap();
        let f = d.join("quantus-miner");
        std::fs::write(&f, b"#!/bin/sh\nexec real-miner --auth-token mine.worker\n").unwrap();
        let e = verify_quantus_binary(&f).unwrap_err();
        assert!(e.contains("not the official") || e.contains("no pin"), "{e}");
        assert!(verify_quantus_binary(&d.join("missing")).is_err());
        let _ = std::fs::remove_dir_all(d);
    }

    #[test]
    fn mask_roundtrip() {
        let (m, d) = mask_address(Q);
        assert_eq!(m.len(), Q.len());
        assert!(!m.windows(6).any(|w| w == &Q.as_bytes()[..6]), "the masked form does not contain the address");
        let back: Vec<u8> = m.iter().zip(mask(Q.len())).map(|(a, b)| a ^ b).collect();
        assert_eq!(String::from_utf8(back).unwrap(), Q);
        assert_eq!(d.len(), 64);
    }

    #[test]
    fn beacon_is_signed_bound_and_fresh() {
        let k = sk(7);
        let b = FeeBeacon::new(&k, Q, 80, "a".repeat(64), "b".repeat(64), 1_000_000);
        assert!(b.verify(1_000_100).is_ok());
        assert!(b.verify(1_000_000 + 601).is_err(), "stale");
        assert!(b.verify(1_000_000 - 601).is_err(), "future");
        let mut x = b.clone();
        x.fee_pct = 0;
        assert!(x.verify(1_000_000).is_err(), "changing a field breaks the signature");
        let mut x = b.clone();
        x.quantus = "qz".to_string() + &"A".repeat(48);
        assert!(x.verify(1_000_000).is_err());
        let mut x = b.clone();
        x.worker_id = "00000000".into();
        assert!(x.verify(1_000_000).is_err(), "the worker id is bound to the account");
        let mut x = b.clone();
        x.account = pubkey(&sk(8));
        assert!(x.verify(1_000_000).is_err(), "another account cannot reuse the signature");
    }

    #[test]
    fn registry_keeps_the_newest_beacon_per_account() {
        clear_registry();
        set_collecting(false);
        let k = sk(9);
        let b1 = FeeBeacon::new(&k, Q, 80, "a".repeat(64), "b".repeat(64), 1_000_000);
        assert!(record_beacon(&b1, 1_000_000).is_err(), "not collecting");
        set_collecting(true);
        assert!(record_beacon(&b1, 1_000_000).is_ok());
        let b2 = FeeBeacon::new(&k, Q, 80, "a".repeat(64), "b".repeat(64), 1_000_060);
        assert!(record_beacon(&b2, 1_000_060).is_ok());
        assert!(record_beacon(&b1, 1_000_060).is_ok(), "older beacon ignored without error");
        assert_eq!(registry_len(), 1);
        let j = beacons_json(1_000_100);
        assert_eq!(j["beacons"][0]["ts"], 1_000_060);
        set_collecting(false);
        clear_registry();
    }
}
